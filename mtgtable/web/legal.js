function render(root, title, sections) {
  root.classList.add("legal");
  root.replaceChildren(el("h2", null, title),
    el("p", "draft", "この文面は下書きです。公開の前に、運営者が内容を確かめて直してください。"));
  for (const [heading, items] of sections) {
    const ul = el("ul");
    for (const text of items) ul.append(el("li", null, text));
    root.append(el("h3", null, heading), ul);
  }
}

export function renderTerms(root, config) { render(root, "利用規約", termsSections(config)); }
export function renderPrivacy(root, config) { render(root, "プライバシー", privacySections(config)); }
